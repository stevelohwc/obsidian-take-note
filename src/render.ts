// Pure markdown rendering and note-section helpers (no Obsidian imports).
import type { MeetingNotes } from "./extract.ts";

export const AI_START = "<!-- meeting-copilot:ai:start -->";
export const AI_END = "<!-- meeting-copilot:ai:end -->";
export const TX_START = "<!-- meeting-copilot:transcript:start -->";
export const TX_END = "<!-- meeting-copilot:transcript:end -->";

export interface RenderOptions {
	linkPeople: boolean;
	tasksEmoji: boolean; // Tasks-plugin style 📅 / ⏫ markers
	generatedAt: string; // e.g. "2026-11-19 15:40"
	model: string;
}

/** Make a name safe to use inside [[ ]]. */
export function personLink(name: string, link: boolean): string {
	const clean = name.replace(/[[\]|#^\\/:*?"<>]/g, "").trim();
	if (!clean) return "";
	// Unrecognised voices ("Speaker 2") and placeholders never become links.
	return link && !/^(speaker \d+|unknown)$/i.test(clean) ? `[[${clean}]]` : clean;
}

const PRIORITY_EMOJI: Record<string, string> = { high: "⏫", medium: "🔼", low: "🔽" };
const TYPE_LABEL: Record<string, string> = { bug: "Bug", feature: "Feature", task: "Task", improvement: "Improvement" };

/** Prefix every line so multi-line text stays inside a callout. */
function quote(text: string): string {
	return text
		.split("\n")
		.map((l) => (l.trim() ? `> ${l}` : ">"))
		.join("\n");
}

function oneLine(s: string): string {
	return s.replace(/\s*\n+\s*/g, " ").trim();
}

export function renderMeeting(m: MeetingNotes, o: RenderOptions): string {
	// "Alice, Bob" / "Alice and Bob" -> [[Alice]], [[Bob]]
	const who = (n: string | null) =>
		n
			? n
					.split(/\s*(?:,|&|\band\b|\/)\s*/i)
					.map((p) => personLink(p, o.linkPeople))
					.filter(Boolean)
					.join(", ")
			: "";
	const task = (s: string) => oneLine(s).replace(/[.;]+$/, "");
	const out: string[] = [AI_START];

	if (m.summary.length) {
		out.push("> [!summary] Summary", ...m.summary.map((s) => `> - ${oneLine(s)}`), "");
	}
	if (m.attendees.length) {
		out.push(`**Attendees:** ${m.attendees.map((a) => who(a)).filter(Boolean).join(", ")}`, "");
	}

	const section = (title: string, lines: string[]) => {
		if (lines.length) out.push(`## ${title}`, ...lines, "");
	};

	section(
		"✅ Decisions",
		m.decisions.map((d) => `- ${oneLine(d)}`),
	);

	section(
		"📌 Action items",
		m.action_items.map((a) => {
			let line = `- [ ] ${task(a.task)}`;
			if (a.owner) line += ` — ${who(a.owner)}`;
			if (o.tasksEmoji) {
				if (a.priority) line += ` ${PRIORITY_EMOJI[a.priority]}`;
				if (a.due) line += ` 📅 ${a.due}`;
			} else if (a.due) {
				line += ` (due ${a.due})`;
			}
			return line;
		}),
	);

	section(
		"❓ Open questions",
		m.questions.map((q) => `- ${oneLine(q.question)}${q.ask ? ` — ask ${who(q.ask)}` : ""}`),
	);

	if (m.tickets.length) {
		out.push("## 🎫 Tickets");
		m.tickets.forEach((t, i) => {
			out.push(`### ${i + 1}. [${TYPE_LABEL[t.type] ?? "Task"}] ${oneLine(t.title)}`);
			const meta: string[] = [];
			if (t.priority) meta.push(`**Priority:** ${t.priority}`);
			if (t.owner) meta.push(`**Owner:** ${who(t.owner)}`);
			if (meta.length) out.push(meta.join(" · "));
			if (t.description) out.push("", t.description.trim());
			if (t.acceptance_criteria.length) {
				out.push("", "**Acceptance criteria**", ...t.acceptance_criteria.map((c) => `- ${oneLine(c)}`));
			}
			out.push("");
		});
	}

	if (m.ai_assignments.length) {
		out.push("## 🤖 AI assignments");
		for (const a of m.ai_assignments) {
			out.push(`- [ ] 🤖 ${task(a.task)}`);
			if (a.prompt) out.push("", "> [!example]- Prompt", quote(a.prompt.trim()));
			out.push("");
		}
	}

	if (m.by_person.length) {
		out.push("## 👥 By person");
		for (const p of m.by_person) {
			const unknown = /^Speaker \d+$/i.test(p.name);
			out.push(`### ${unknown ? p.name : who(p.name)}`);
			if (p.summary) out.push(oneLine(p.summary));
			const sub = (label: string, items: string[]) => {
				if (items.length) out.push(`- **${label}**`, ...items.map((i) => `    - ${oneLine(i)}`));
			};
			sub("Updates", p.updates);
			sub("Will do", p.commitments);
			sub("Asked / needs", p.asks);
			out.push("");
		}
	}

	section(
		"⚠️ Risks & blockers",
		m.risks.map((r) => `- ${oneLine(r)}`),
	);
	section(
		"📝 Worth remembering",
		m.notes.map((n) => `- ${oneLine(n)}`),
	);
	section(
		"🔜 Follow up next time",
		m.follow_ups.map((f) => `- ${oneLine(f)}`),
	);

	out.push(`<small>Generated by Meeting Copilot · ${o.model} · ${o.generatedAt}</small>`, AI_END);
	return out.join("\n");
}

export function renderTranscript(text: string, audioLink: string | null, meta: string, speakerSession?: string): string {
	const lines = [TX_START];
	if (speakerSession) lines.push(`<!-- mc-speakers:${speakerSession} -->`);
	lines.push("## Transcript");
	if (audioLink) lines.push(audioLink, "");
	lines.push(`> [!quote]- Transcript (${meta})`, quote(text.trim() || "(no speech detected)"), TX_END);
	return lines.join("\n");
}

/** Split frontmatter from body. */
export function splitFrontmatter(content: string): { fm: string; body: string } {
	const m = content.match(/^---\r?\n[\s\S]*?\r?\n---\r?\n?/);
	return m ? { fm: m[0], body: content.slice(m[0].length) } : { fm: "", body: content };
}

/** Replace the block between markers, or insert it if missing. */
export function upsertBlock(
	content: string,
	start: string,
	end: string,
	block: string,
	where: "afterTitle" | "end",
): string {
	const s = content.indexOf(start);
	const e = content.indexOf(end, s === -1 ? 0 : s);
	if (s !== -1 && e !== -1) {
		return content.slice(0, s) + block + content.slice(e + end.length);
	}
	if (where === "end") {
		return content.replace(/\s*$/, "") + "\n\n" + block + "\n";
	}
	const { fm, body } = splitFrontmatter(content);
	const h1 = body.match(/^# .*(\r?\n|$)/m);
	if (h1 && h1.index !== undefined && body.slice(0, h1.index).trim() === "") {
		const at = h1.index + h1[0].length;
		return fm + body.slice(0, at) + "\n" + block + "\n\n" + body.slice(at).replace(/^\s+/, "");
	}
	return fm + block + "\n\n" + body.replace(/^\s+/, "");
}

/** Text between markers (exclusive), or null. */
export function getBlock(content: string, start: string, end: string): string | null {
	const s = content.indexOf(start);
	if (s === -1) return null;
	const e = content.indexOf(end, s);
	if (e === -1) return null;
	return content.slice(s + start.length, e);
}

export function removeBlock(content: string, start: string, end: string): string {
	const s = content.indexOf(start);
	if (s === -1) return content;
	const e = content.indexOf(end, s);
	if (e === -1) return content;
	return content.slice(0, s) + content.slice(e + end.length);
}

/**
 * Split a meeting note into what the AI should read:
 * the user's own notes (everything except our generated blocks and frontmatter)
 * and the transcript text (callout prefixes stripped).
 */
export function collectSources(content: string): { notes: string; transcript: string } {
	const txBlock = getBlock(content, TX_START, TX_END) ?? "";
	const transcript = txBlock
		.split("\n")
		.filter((l) => l.startsWith(">") && !/^>\s*\[!quote\]/.test(l))
		.map((l) => l.replace(/^>\s?/, ""))
		.join("\n")
		.replace(/^\(no speech detected\)$/m, "")
		.trim();
	let rest = removeBlock(removeBlock(content, AI_START, AI_END), TX_START, TX_END);
	rest = splitFrontmatter(rest).body;
	const notes = rest
		.replace(/!\[\[[^\]]+\]\]/g, "") // embeds (audio, images)
		.replace(/^## My notes\s*$/m, "")
		.replace(/\n{3,}/g, "\n\n")
		.trim();
	return { notes, transcript };
}

/** Remove whisper's typical repetition loops and blank lines. */
export function cleanTranscript(lines: string[]): string[] {
	const out: string[] = [];
	let last = "";
	let repeats = 0;
	for (const raw of lines) {
		const line = raw.trim();
		if (!line) continue;
		const text = line.replace(/^\[[\d:.]+\]\s*/, "").toLowerCase();
		if (text === last) {
			if (++repeats >= 2) continue; // allow one repeat, drop loops
		} else {
			repeats = 0;
		}
		last = text;
		out.push(line);
	}
	return out;
}

export function formatClock(ms: number): string {
	const s = Math.floor(ms / 1000);
	const h = Math.floor(s / 3600);
	const m = Math.floor((s % 3600) / 60);
	const sec = s % 60;
	const pad = (n: number) => String(n).padStart(2, "0");
	return h ? `${h}:${pad(m)}:${pad(sec)}` : `${pad(m)}:${pad(sec)}`;
}

export function safeFileName(name: string): string {
	return name
		.replace(/[\\/:*?"<>|#^[\]]/g, " ")
		.replace(/\s+/g, " ")
		.trim()
		.slice(0, 80);
}

/** Session id of the speaker data for this note's transcript, if it was separated by speaker. */
export function speakerSessionId(content: string): string | null {
	const block = getBlock(content, TX_START, TX_END);
	return block?.match(/<!-- mc-speakers:([a-z0-9]+) -->/i)?.[1] ?? null;
}

/**
 * Add or replace this meeting's line in a People note's "## Notes" section:
 *   - [[2026-11-19 – Bot Flow Review]] — summary
 * Re-running replaces the existing line for the same meeting instead of duplicating it.
 */
export function upsertPersonLine(content: string, meetingName: string, summary: string): string {
	const line = `- [[${meetingName}]] — ${oneLine(summary)}`;
	const lines = content.split("\n");
	const existing = lines.findIndex((l) => l.startsWith(`- [[${meetingName}]]`) || l.startsWith(`- [[${meetingName}|`));
	if (existing !== -1) {
		lines[existing] = line;
		return lines.join("\n");
	}
	const heading = lines.findIndex((l) => /^##\s+Notes\s*$/i.test(l));
	if (heading === -1) return content.replace(/\s*$/, "") + `\n\n## Notes\n\n${line}\n`;
	// Insert after the last bullet of the Notes section (before the next heading).
	let end = heading + 1;
	for (let i = heading + 1; i < lines.length && !/^#{1,6}\s/.test(lines[i]); i++) if (lines[i].trim()) end = i + 1;
	if (end === heading + 1) {
		lines.splice(heading + 1, 0, "", line);
	} else {
		lines.splice(end, 0, line);
	}
	return lines.join("\n");
}
